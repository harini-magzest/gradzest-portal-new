// Writes dist/robots.txt and dist/sitemap.xml. `npm run build` runs it from `postbuild`, before finalize-dist.mjs checks the
// folder. Both files describe the site's address, so they are generated rather than kept in public/ with a hard-coded host.
//
//   SITE_URL   the public address of the website, with no path (default https://gradzest.com: the address index.html's
//              canonical and Open Graph tags already use, so set the same value there if you change it)
//
// The sitemap lists the pages that do not need the API: the home page, the public list pages, the policy pages and every
// blog post (read from src/data/blogPosts.ts). University detail pages come from the database and are not listed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_SITE_URL = 'https://gradzest.com';

const STATIC_PAGES = [
  { path: '/', changefreq: 'weekly', priority: '1.0' },
  { path: '/universities', changefreq: 'weekly', priority: '0.8' },
  { path: '/resources', changefreq: 'weekly', priority: '0.8' },
  { path: '/privacy', changefreq: 'yearly', priority: '0.3' },
  { path: '/terms', changefreq: 'yearly', priority: '0.3' },
];

// Signed-in areas and one-time links. A crawler gets nothing useful from them; this keeps them out of search results.
// It is not access control: those routes are protected by authentication, not by this file.
const PRIVATE_PATHS = [
  '/api/', '/admin', '/appteam', '/board', '/counselor', '/student', '/soc', '/parent/', '/f/',
  '/login', '/forgot-password', '/reset-password', '/verify-email',
];

// The site address without a trailing slash; throws on anything that is not an http(s) origin.
export function normalizeSiteUrl(value = DEFAULT_SITE_URL) {
  let url;
  try { url = new URL(String(value).trim()); } catch { throw new Error(`SITE_URL is not a valid URL: "${value}"`); }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error(`SITE_URL must be http(s): "${value}"`);
  if (url.pathname !== '/' || url.search || url.hash) throw new Error(`SITE_URL must be an origin with no path: "${value}"`);
  return url.origin;
}

// Pulls { slug, publishedAt } out of the blog data file. A slug is paired only with a publishedAt that comes before the next
// slug, so a post missing its date can never borrow the next post's.
export function readBlogPosts(source) {
  const posts = [];
  const re = /\bslug:\s*['"]([A-Za-z0-9-]+)['"]((?:(?!\bslug:)[\s\S])*)/g;
  for (const m of source.matchAll(re)) {
    const date = /\bpublishedAt:\s*['"](\d{4}-\d{2}-\d{2})['"]/.exec(m[2]);
    posts.push({ slug: m[1], publishedAt: date ? date[1] : null });
  }
  return posts;
}

const escapeXml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function buildSitemap({ siteUrl, posts = [] }) {
  const entries = [
    ...STATIC_PAGES.map((p) => ({ loc: siteUrl + (p.path === '/' ? '/' : p.path), changefreq: p.changefreq, priority: p.priority })),
    ...posts.map((p) => ({ loc: `${siteUrl}/resources/${p.slug}`, lastmod: p.publishedAt, changefreq: 'monthly', priority: '0.6' })),
  ];
  const body = entries.map((e) => [
    '  <url>',
    `    <loc>${escapeXml(e.loc)}</loc>`,
    e.lastmod ? `    <lastmod>${e.lastmod}</lastmod>` : null,
    `    <changefreq>${e.changefreq}</changefreq>`,
    `    <priority>${e.priority}</priority>`,
    '  </url>',
  ].filter(Boolean).join('\n')).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

export function buildRobots({ siteUrl }) {
  return [
    '# Generated by scripts/generate-seo.mjs at build time.',
    '# These paths are signed-in areas and one-time links; this file only keeps them out of search results, it does not protect them.',
    'User-agent: *',
    'Allow: /',
    ...PRIVATE_PATHS.map((p) => `Disallow: ${p}`),
    '',
    `Sitemap: ${siteUrl}/sitemap.xml`,
    '',
  ].join('\n');
}

export function generate({ dist = path.join(ROOT, 'dist'), env = process.env, blogSource } = {}) {
  const siteUrl = normalizeSiteUrl(env.SITE_URL || DEFAULT_SITE_URL);
  if (!fs.existsSync(dist)) throw new Error(`generate-seo: ${dist} does not exist: run it after "vite build"`);
  const source = blogSource ?? fs.readFileSync(path.join(ROOT, 'src', 'data', 'blogPosts.ts'), 'utf8');
  const posts = readBlogPosts(source);
  if (!posts.length) throw new Error('generate-seo: found no blog posts in src/data/blogPosts.ts (did its format change?)');
  fs.writeFileSync(path.join(dist, 'robots.txt'), buildRobots({ siteUrl }));
  fs.writeFileSync(path.join(dist, 'sitemap.xml'), buildSitemap({ siteUrl, posts }));
  return { siteUrl, posts: posts.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { siteUrl, posts } = generate();
    console.log(`generate-seo: wrote robots.txt and sitemap.xml for ${siteUrl} (${STATIC_PAGES.length} pages, ${posts} blog posts)`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
